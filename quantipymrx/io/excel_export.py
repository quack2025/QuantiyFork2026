# =============================================================================
# Style Definitions
# =============================================================================

# Colors
HEADER_COLOR = "1F4E79"  # Dark blue
SUBHEADER_COLOR = "2E75B6"  # Medium blue
HIGHLIGHT_COLOR = "BDD7EE"  # Light blue
TOTAL_COLOR = "D9E2F3"  # Very light blue
WHITE = "FFFFFF"
LIGHT_GRAY = "F2F2F2"

# Fonts
HEADER_FONT = Font(bold=True, color=WHITE, size=11)
SUBHEADER_FONT = Font(bold=True, color=WHITE, size=10)
BOLD_FONT = Font(bold=True, size=10)
NORMAL_FONT = Font(size=10)
TITLE_FONT = Font(bold=True, size=14)

# Fills
HEADER_FILL = PatternFill(start_color=HEADER_COLOR, end_color=HEADER_COLOR, fill_type="solid")
SUBHEADER_FILL = PatternFill(start_color=SUBHEADER_COLOR, end_color=SUBHEADER_COLOR, fill_type="solid")
HIGHLIGHT_FILL = PatternFill(start_color=HIGHLIGHT_COLOR, end_color=HIGHLIGHT_COLOR, fill_type="solid")
TOTAL_FILL = PatternFill(start_color=TOTAL_COLOR, end_color=TOTAL_COLOR, fill_type="solid")
STRIPE_FILL = PatternFill(start_color=LIGHT_GRAY, end_color=LIGHT_GRAY, fill_type="solid")

# Borders
THIN_BORDER = Border(
    left=Side(style='thin'),
    right=Side(style='thin'),
    top=Side(style='thin'),
    bottom=Side(style='thin')
)

# Alignments
CENTER = Alignment(horizontal='center', vertical='center')
LEFT = Alignment(horizontal='left', vertical='center')
RIGHT = Alignment(horizontal='right', vertical='center')


def _ensure_openpyxl():
    """Raise error if openpyxl is not available."""
    if not HAS_OPENPYXL:
        raise ImportError(
            "openpyxl is required for Excel export. "
            "Install with: pip install openpyxl"
        )


# =============================================================================
# Excel Workbook Builder
# =============================================================================

class ExcelExporter:
    """
    Professional Excel exporter for market research data.

    Creates formatted Excel workbooks with multiple sheets.
    """

    def __init__(self, title: str = "QuantipyMRX Export"):
        """
        Initialize the Excel exporter.

        Parameters
        ----------
        title : str
            Title for the workbook (used in cover sheet).
        """
        _ensure_openpyxl()
        self.wb = Workbook()
        self.title = title
        self._sheet_count = 0

        # Remove default sheet
        if 'Sheet' in self.wb.sheetnames:
            del self.wb['Sheet']

    def add_cover_sheet(
        self,
        dataset_name: str,
        case_count: int,
        metadata: Optional[Dict[str, Any]] = None,
    ):
        """
        Add a cover sheet with export information.

        Parameters
        ----------
        dataset_name : str
            Name of the dataset.
        case_count : int
            Number of cases in the dataset.
        metadata : dict, optional
            Additional metadata to display.
        """
        ws = self.wb.create_sheet("Cover", 0)

        # Title
        ws['B2'] = self.title
        ws['B2'].font = Font(bold=True, size=20)

        # Export info
        info_rows = [
            ("Dataset:", dataset_name),
            ("Cases:", f"{case_count:,}"),
            ("Export Date:", datetime.now().strftime("%Y-%m-%d %H:%M")),
            ("Generated by:", "QuantipyMRX"),
        ]

        if metadata:
            for key, value in metadata.items():
                info_rows.append((f"{key}:", str(value)))

        row = 4
        for label, value in info_rows:
            ws[f'B{row}'] = label
            ws[f'B{row}'].font = BOLD_FONT
            ws[f'C{row}'] = value
            row += 1

        # Adjust column widths
        ws.column_dimensions['A'].width = 5
        ws.column_dimensions['B'].width = 20
        ws.column_dimensions['C'].width = 40

    def add_frequency(
        self,
        result: "FrequencyResult",
        sheet_name: Optional[str] = None,
    ):
        """
        Add a frequency table sheet.

        Parameters
        ----------
        result : FrequencyResult
            The frequency result to export.
        sheet_name : str, optional
            Name for the sheet. Auto-generated if not provided.
        """
        sheet_name = sheet_name or self._make_sheet_name(result.variable)
        ws = self.wb.create_sheet(sheet_name)

        # Title
        ws['A1'] = result.label or result.variable
        ws['A1'].font = TITLE_FONT
        ws.merge_cells('A1:D1')

        # Stats row
        ws['A2'] = f"Base: {result.base:,}"
        if result.mean is not None:
            ws['B2'] = f"Mean: {result.mean:.2f}"

        # Headers
        headers = ['Code', 'Label', 'Count', 'Percent']
        for col, header in enumerate(headers, 1):
            cell = ws.cell(row=4, column=col, value=header)
            cell.font = HEADER_FONT
            cell.fill = HEADER_FILL
            cell.alignment = CENTER
            cell.border = THIN_BORDER

        # Data
        for i, row_data in enumerate(result.table.itertuples(index=False), 5):
            for col, value in enumerate(row_data, 1):
                cell = ws.cell(row=i, column=col, value=value)
                cell.border = THIN_BORDER
                cell.alignment = RIGHT if col > 1 else LEFT

                # Format percentages
                if col == 4 and isinstance(value, (int, float)):
                    cell.number_format = '0.0%'
                    cell.value = value / 100

                # Stripe alternate rows
                if i % 2 == 0:
                    cell.fill = STRIPE_FILL

        # Adjust column widths
        ws.column_dimensions['A'].width = 10
        ws.column_dimensions['B'].width = 40
        ws.column_dimensions['C'].width = 12
        ws.column_dimensions['D'].width = 12

    def add_crosstab(
        self,
        result: "CrosstabResult",
        sheet_name: Optional[str] = None,
        show_counts: bool = True,
        show_col_pct: bool = True,
    ):
        """
        Add a crosstab sheet.

        Parameters
        ----------
        result : CrosstabResult
            The crosstab result to export.
        sheet_name : str, optional
            Name for the sheet.
        show_counts : bool
            Whether to show count table.
        show_col_pct : bool
            Whether to show column percentage table.
        """
        sheet_name = sheet_name or self._make_sheet_name(f"{result.x}_x_{result.y}")
        ws = self.wb.create_sheet(sheet_name)

        row = 1

        # Title
        ws['A1'] = f"{result.x_label} by {result.y_label}"
        ws['A1'].font = TITLE_FONT
        row = 3

        # Stats
        ws[f'A{row}'] = f"Base: {result.total_base:,}"
        if result.chi2 is not None:
            ws[f'B{row}'] = f"Chi-square: {result.chi2:.2f}"
            ws[f'C{row}'] = f"p-value: {result.chi2_pvalue:.4f}"
        row += 2

        # Column percentages table
        if show_col_pct and result.col_pct is not None:
            ws[f'A{row}'] = "Column Percentages"
            ws[f'A{row}'].font = BOLD_FONT
            row += 1
            row = self._write_dataframe(ws, result.col_pct, row, is_percent=True)
            row += 2

        # Counts table
        if show_counts and result.counts is not None:
            ws[f'A{row}'] = "Counts"
            ws[f'A{row}'].font = BOLD_FONT
            row += 1
            row = self._write_dataframe(ws, result.counts, row, is_percent=False)

    def add_awareness(
        self,
        result: "AwarenessSummary",
        sheet_name: Optional[str] = None,
    ):
        """
        Add an awareness summary sheet.

        Parameters
        ----------
        result : AwarenessSummary
            The awareness summary to export.
        sheet_name : str, optional
            Name for the sheet.
        """
        sheet_name = sheet_name or self._make_sheet_name(result.group_name)
        ws = self.wb.create_sheet(sheet_name)

        # Title
        ws['A1'] = result.display_name[:100] if result.display_name else result.group_name
        ws['A1'].font = TITLE_FONT
        ws.merge_cells('A1:E1')

        # Stats
        ws['A2'] = f"Base: {result.total_base:,}"
        ws['C2'] = f"Average Awareness: {result.average_awareness:.1f}%"

        # Headers
        headers = ['Item', 'Base', 'Aware', 'Awareness %']
        for col, header in enumerate(headers, 1):
            cell = ws.cell(row=4, column=col, value=header)
            cell.font = HEADER_FONT
            cell.fill = HEADER_FILL
            cell.alignment = CENTER
            cell.border = THIN_BORDER

        # Data
        for i, row_data in enumerate(result.awareness_table.itertuples(index=False), 5):
            # Skip 'variable' column, show item_label instead
            values = [row_data[1], row_data[2], row_data[3], row_data[4]]  # item_label, base, aware_count, awareness_pct
            for col, value in enumerate(values, 1):
                cell = ws.cell(row=i, column=col, value=value)
                cell.border = THIN_BORDER
                cell.alignment = RIGHT if col > 1 else LEFT

                # Format percentages
                if col == 4 and isinstance(value, (int, float)):
                    cell.number_format = '0.0%'
                    cell.value = value / 100

                if i % 2 == 0:
                    cell.fill = STRIPE_FILL

        # Column widths
        ws.column_dimensions['A'].width = 50
        ws.column_dimensions['B'].width = 12
        ws.column_dimensions['C'].width = 12
        ws.column_dimensions['D'].width = 15

    def add_grid_summary(
        self,
        result: "GridSummary",
        sheet_name: Optional[str] = None,
    ):
        """
        Add a grid/scale summary sheet.

        Parameters
        ----------
        result : GridSummary
            The grid summary to export.
        sheet_name : str, optional
            Name for the sheet.
        """
        sheet_name = sheet_name or self._make_sheet_name(result.group_name)
        ws = self.wb.create_sheet(sheet_name)

        # Title
        ws['A1'] = result.display_name[:100] if result.display_name else result.group_name
        ws['A1'].font = TITLE_FONT
        ws.merge_cells('A1:F1')

        # Stats
        ws['A2'] = f"Scale: {result.scale_min} to {result.scale_max}"
        if result.overall_mean:
            ws['C2'] = f"Overall Mean: {result.overall_mean:.2f}"

        # Determine columns based on data
        all_cols = list(result.summary_table.columns)
        display_cols = ['item_label', 'base', 'mean', 'std_dev', 'top_2_box', 'bottom_2_box']
        if 'nps_score' in all_cols:
            display_cols.append('nps_score')

        header_labels = {
            'item_label': 'Item',
            'base': 'Base',
            'mean': 'Mean',
            'std_dev': 'Std Dev',
            'top_2_box': 'Top 2 Box',
            'bottom_2_box': 'Bottom 2 Box',
            'nps_score': 'NPS Score',
        }

        # Headers
        for col, col_name in enumerate(display_cols, 1):
            if col_name in all_cols or col_name == 'item_label':
                cell = ws.cell(row=4, column=col, value=header_labels.get(col_name, col_name))
                cell.font = HEADER_FONT
                cell.fill = HEADER_FILL
                cell.alignment = CENTER
                cell.border = THIN_BORDER

        # Data
        for i, row in enumerate(result.summary_table.itertuples(index=False), 5):
            row_dict = result.summary_table.iloc[i-5].to_dict()
            for col, col_name in enumerate(display_cols, 1):
                if col_name in row_dict or col_name == 'item_label':
                    value = row_dict.get(col_name)
                    cell = ws.cell(row=i, column=col, value=value)
                    cell.border = THIN_BORDER
                    cell.alignment = RIGHT if col > 1 else LEFT

                    # Format percentages for box scores
                    if col_name in ['top_2_box', 'bottom_2_box'] and value is not None:
                        cell.number_format = '0.0%'
                        cell.value = value / 100

                    if i % 2 == 0:
                        cell.fill = STRIPE_FILL

        # Column widths
        ws.column_dimensions['A'].width = 50
        for col in range(2, 8):
            ws.column_dimensions[get_column_letter(col)].width = 12

    def add_top_of_mind(
        self,
        result: "TopOfMindSummary",
        sheet_name: Optional[str] = None,
    ):
        """
        Add a Top of Mind summary sheet.

        Parameters
        ----------
        result : TopOfMindSummary
            The TOM summary to export.
        sheet_name : str, optional
            Name for the sheet.
        """
        sheet_name = sheet_name or self._make_sheet_name(result.group_name)
        ws = self.wb.create_sheet(sheet_name)

        # Title
        ws['A1'] = result.display_name[:100] if result.display_name else result.group_name
        ws['A1'].font = TITLE_FONT
        ws.merge_cells('A1:E1')

        # Stats
        ws['A2'] = f"Base: {result.total_base:,}"
        ws['C2'] = f"Mentioners: {result.total_mentioners:,}"

        row = 4

