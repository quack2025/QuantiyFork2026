def export_frequency_to_excel(
    result: "FrequencyResult",
    filepath: Union[str, Path],
):
    """
    Export a single frequency result to Excel.

    Parameters
    ----------
    result : FrequencyResult
        The frequency result.
    filepath : str or Path
        Output file path.
    """
    exporter = ExcelExporter(title="Frequency Analysis")
    exporter.add_frequency(result)
    exporter.save(filepath)


def export_crosstab_to_excel(
    result: "CrosstabResult",
    filepath: Union[str, Path],
):
    """
    Export a single crosstab result to Excel.

    Parameters
    ----------
    result : CrosstabResult
        The crosstab result.
    filepath : str or Path
        Output file path.
    """
    exporter = ExcelExporter(title="Crosstab Analysis")
    exporter.add_crosstab(result)
    exporter.save(filepath)


def export_processing_results(
    grouped_results: Dict[str, Any],
    filepath: Union[str, Path],
    dataset_name: str = "Survey",
    case_count: int = 0,
):
    """
    Export all grouped processing results to Excel.

    Parameters
    ----------
    grouped_results : dict
        Dictionary of group names to result objects.
    filepath : str or Path
        Output file path.
    dataset_name : str
        Name of the dataset.
    case_count : int
        Number of cases.
    """
    from quantipymrx.analysis.grouping import (
        AwarenessSummary, GridSummary, TopOfMindSummary, GroupedFrequency
    )

    exporter = ExcelExporter(title=f"{dataset_name} Analysis")
    exporter.add_cover_sheet(dataset_name, case_count)

    for name, result in grouped_results.items():
        try:
            if isinstance(result, AwarenessSummary):
                exporter.add_awareness(result)
            elif isinstance(result, GridSummary):
                exporter.add_grid_summary(result)
            elif isinstance(result, TopOfMindSummary):
                exporter.add_top_of_mind(result)
            elif isinstance(result, GroupedFrequency):
                # Convert to DataFrame for generic export
                exporter.add_dataframe(result.frequency_table, name, result.display_name)
        except Exception as e:
            logger.warning(f"Failed to export {name}: {e}")

    exporter.save(filepath)


